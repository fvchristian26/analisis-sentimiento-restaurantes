# CÉLDA 5: Carga de los 3 Modelos con Pipelines (Corregida)
# ==========================================
import time
from transformers import pipeline

# Definir los tres modelos diferentes y válidos en Hugging Face
modelos_id = {
    "RoBERTuito": "pysentimiento/robertuito-sentiment-analysis",
    "BETO-Sentiment": "finiteautomata/beto-sentiment-analysis",
    "XLM-RoBERTa-Sentiment": "cardiffnlp/twitter-xlm-roberta-base-sentiment"
}

# Inicializar los pipelines utilizando la GPU (device=0)
pipelines = {}
for nombre, model_id in modelos_id.items():
    print(f"Cargando modelo: {nombre} ({model_id})...")
    pipelines[nombre] = pipeline(
        task="text-classification",
        model=model_id,
        device=0
    )

print("¡Todos los modelos se cargaron exitosamente!")

# ==========================================
# CÉLDA 6: Inferencia, Medición de Latencia y Normalización
# ==========================================
textos = df['comentario'].astype(str).tolist()
etiquetas_reales = df['sentimiento'].str.strip().str.upper().tolist()

resultados_inferencia = {}
tiempos_ejecucion = {}

for nombre, pipe in pipelines.items():
    print(f"Ejecutando inferencia con {nombre}...")

    inicio = time.time()
    predicciones_raw = pipe(textos, batch_size=16)
    fin = time.time()

    tiempo_total = fin - inicio
    tiempo_promedio = tiempo_total / len(textos)
    tiempos_ejecucion[nombre] = {
        "tiempo_total": tiempo_total,
        "tiempo_promedio": tiempo_promedio
    }

    # Normalización de etiquetas de salida a formato estándar (NEG, NEU, POS)
    preds_normalizadas = []
    for pred in predicciones_raw:
        label = pred['label'].upper()
        if 'NEG' in label or 'NEGATIVE' in label or '1' in label:
            preds_normalizadas.append('NEG')
        elif 'NEU' in label or 'NEUTRAL' in label or '2' in label:
            preds_normalizadas.append('NEU')
        else:
            preds_normalizadas.append('POS')

    resultados_inferencia[nombre] = preds_normalizadas

print("¡Inferencia y normalización completadas con éxito!")

# ==========================================
# CÉLDA 7: Evaluación de Métricas de Desempeño
# ==========================================
from sklearn.metrics import accuracy_score, precision_recall_fscore_support

metricas_totales = []

for nombre in modelos_id.keys():
    preds = resultados_inferencia[nombre]

    acc = accuracy_score(etiquetas_reales, preds)
    prec, rec, f1, _ = precision_recall_fscore_support(
        etiquetas_reales, preds, average='weighted', zero_division=0
    )

    metricas_totales.append({
        "Modelo": nombre,
        "Accuracy": round(acc, 4),
        "Precision": round(prec, 4),
        "Recall": round(rec, 4),
        "F1-Score": round(f1, 4),
        "Tiempo Promedio (s/res)": round(tiempos_ejecucion[nombre]["tiempo_promedio"], 5)
    })

df_metricas = pd.DataFrame(metricas_totales)
print("\n--- TABLA COMPARATIVA DE DESEMPEÑO ---")
display(df_metricas)

